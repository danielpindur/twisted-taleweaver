namespace TwistedTaleweaver.Api.Creatures.Entities.Enums;

/// <summary>
/// Determines what a character is trained to do, their special abilities, and how they contribute to the adventuring party
/// </summary>
public enum CharacterClass
{
    /// <summary>
    /// Savage warrior with unmatched strength and battle fury.
    /// </summary>
    Barbarian = 1,

    /// <summary>
    /// Inspires allies and confounds foes with magical performances
    /// </summary>
    Bard,

    /// <summary>
    /// Channels divine power to heal wounds and smite enemies.
    /// </summary>
    Cleric,

    /// <summary>
    /// Shapes the wild's power to transform and command nature.
    /// </summary>
    Druid,

    /// <summary>
    /// Expert combatant mastering weapons and battlefield tactics.
    /// </summary>
    Fighter,

    /// <summary>
    /// Harnesses ki for swift strikes and disciplined defense.
    /// </summary>
    Monk,

    /// <summary>
    /// Holy knight smiting evil and protecting the righteous.
    /// </summary>
    Paladin,

    /// <summary>
    /// Tracks foes and excels at ranged attacks in the wild.
    /// </summary>
    Ranger,

    /// <summary>
    /// Stealthy infiltrator skilled in stealth, locks, and backstabs.
    /// </summary>
    Rogue,

    /// <summary>
    /// Wields raw magic born of innate arcane bloodlines.
    /// </summary>
    Sorcerer,

    /// <summary>
    /// Draws eldritch power from pacts with mysterious patrons.
    /// </summary>
    Warlock,

    /// <summary>
    /// Studies arcane lore to cast a variety of potent spells.
    /// </summary>
    Wizard,

    /// <summary>
    /// Crafts magical gadgets, constructs, and alchemical devices.
    /// </summary>
    Artificer,

    /// <summary>Brews potions for healing, bombs, and transmutations.
    /// </summary>
    Alchemist,

    /// <summary>
    /// Fights alongside a bonded beast companion in seamless synergy.
    /// </summary>
    Beastmaster,

    /// <summary>
    /// Trades vitality for devastating blood magic spells.
    /// </summary>
    Bloodmage,

    /// <summary>
    /// Manipulates time to hasten allies and delay foes.
    /// </summary>
    Chronomancer,

    /// <summary>
    /// Commands elemental forces of fire, water, air, and earth.
    /// </summary>
    Elementalist,

    /// <summary>
    /// Wields a cursed weapon infused with dark pact magic.
    /// </summary>
    Hexblade,

    /// <summary>
    /// Commands undead minions and wields the power of death.
    /// </summary>
    Necromancer,

    /// <summary>
    /// Harnesses psychic powers like telepathy and telekinesis.
    /// </summary>
    Psion,

    /// <summary>
    /// Moves in shadows to strike unseen and vanish at will.
    /// </summary>
    Shadowdancer,

    /// <summary>
    /// Imbues weapons with magic for lethal sword-and-spell combat.
    /// </summary>
    Spellblade,

    /// <summary>
    /// Conjures creatures from other realms to fight by their side.
    /// </summary>
    Summoner,

    /// <summary>
    /// Stands guard over nature with ancient magic and resolve.
    /// </summary>
    Warden
}