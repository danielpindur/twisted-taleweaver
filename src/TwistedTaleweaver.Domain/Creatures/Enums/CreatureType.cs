namespace TwistedTaleweaver.Domain.Creatures.Enums;

/// <summary>
/// Creature type (e.g., 'Aberration', 'Undead', 'Fiend')
/// </summary>
public enum CreatureType
{
    /// <summary>
    /// Mind-bending beings defying natural law with alien anatomies.
    /// </summary>
    Aberration = 1,

    /// <summary>
    /// Non-sapient animals guided by instinct and natural ferocity.
    /// </summary>
    Beast,

    /// <summary>
    /// Divine emissaries radiating holy light from celestial realms.
    /// </summary>
    Celestial,

    /// <summary>
    /// Animated constructs built of stone, metal, or arcane machinery.
    /// </summary>
    Construct,

    /// <summary>
    /// Ancient reptilian titans wielding elemental breath and claws.
    /// </summary>
    Dragon,

    /// <summary>
    /// Embodiments of primal elements: fire, water, earth, and air.
    /// </summary>
    Elemental,

    /// <summary>
    /// Mischievous nature spirits dancing between beauty and mischief.
    /// </summary>
    Fey,

    /// <summary>
    /// Malignant entities from infernal planes craving mortal souls.
    /// </summary>
    Fiend,

    /// <summary>
    /// Towering humanoids of immense size and fearsome strength.
    /// </summary>
    Giant,

    /// <summary>
    /// Sapient species with humanoid forms and varied cultures.
    /// </summary>
    Humanoid,

    /// <summary>
    /// Beasts warped by magic or nature into monstrous forms.
    /// </summary>
    Monstrosity,

    /// <summary>
    /// Amorphous creatures that engulf and dissolve all they touch.
    /// </summary>
    Ooze,

    /// <summary>
    /// Animated vegetation pulsing with the lifeforce of nature.
    /// </summary>
    Plant,

    /// <summary>
    /// Reanimated corpses driven by dark necromantic powers.
    /// </summary>
    Undead,

    /// <summary>
    /// Ethereal wanderers traversing the realms of dream and thought.
    /// </summary>
    Dreamwalker,

    /// <summary>
    /// Half-seen beings drifting between the material and beyond.
    /// </summary>
    Ethereal,

    /// <summary>
    /// Minds incarnate shaping reality with pure mental prowess.
    /// </summary>
    Psychic,

    /// <summary>
    /// Creatures forged from darkness, stalking in eternal night.
    /// </summary>
    Shadowspawn,

    /// <summary>
    /// Living steam and metal forged into hissing constructs.
    /// </summary>
    Steamborn,

    /// <summary>
    /// Beings of pure light banishing shadows with brilliant radiance.
    /// </summary>
    Luminarch,

    /// <summary>
    /// Time-wreathed dragons bending ages with each thunderous breath.
    /// </summary>
    Chronowyrm,

    /// <summary>
    /// Molten metal guardians smithing war in volcanic fury.
    /// </summary>
    Forgeborn,

    /// <summary>
    /// Colossal sea predators riding waves of crushing might.
    /// </summary>
    Tidehunter,

    /// <summary>
    /// Cosmic entities woven from stardust and stellar energy.
    /// </summary>
    Starforged
}